"""Hybrid Ollama client for Sugarscape.

The hybrid mode combines two locally served Ollama models:

* nimble-v3 handles simple, low-risk decisions.
* qwen3 handles difficult decisions, or decisions nimble-v3 could not answer.

Both models are reached through the same Ollama endpoint.  nimble-v3 is a
decision model, so it is called through Ollama's System One endpoint
(``/v1/systemone``); qwen3 is a regular generative model called through
``/api/generate`` with thinking disabled.  A decision is considered difficult
when an agent has many candidate cells, when the best candidates have almost
the same value, or when the agent is close to starvation.  Conversations are
escalated in a similar way when an agent is short on resources or when the
speakers belong to different tribes.
"""

import os
from concurrent.futures import ThreadPoolExecutor

from .nimble_client import NimbleClient
from .ollama_client import OllamaClient


class HybridClient:
    def __init__(self, endpoint="http://127.0.0.1:11434", nimbleModel="nimble-v3:9b",
                 qwenModel="qwen3:8b", timeout=120, options=None,
                 candidateThreshold=16, wealthMargin=0.1, scarcityFactor=2.0):
        self.endpoint = endpoint.rstrip("/")
        self.nimbleModel = nimbleModel
        self.qwenModel = qwenModel
        self.timeout = timeout
        self.options = dict(options or {})
        self.candidateThreshold = max(1, int(candidateThreshold))
        self.wealthMargin = max(0.0, float(wealthMargin))
        self.scarcityFactor = max(0.0, float(scarcityFactor))
        # nimble-v3 is an Ollama decision model served by /v1/systemone, while
        # qwen3 is a regular generative model served by /api/generate.
        self.nimble = NimbleClient(self.endpoint, self.nimbleModel, self.timeout, self.options)
        self.qwen = OllamaClient(self.endpoint, self.qwenModel, self.timeout, self.options, think=False)
        try:
            defaultParallel = os.environ.get("OLLAMA_NUM_PARALLEL", "1")
            self.numParallel = max(1, int(os.environ.get("HYBRID_NUM_PARALLEL", defaultParallel)))
        except ValueError:
            self.numParallel = 1

    def _isDifficultDecision(self, record):
        """Return True when a movement decision should be made by qwen3."""
        candidates = record.get("candidates") or []
        if len(candidates) <= 1:
            return False
        if len(candidates) > self.candidateThreshold:
            return True

        wealths = sorted((float(candidate.get("wealth", 0.0) or 0.0) for candidate in candidates),
                         reverse=True)
        bestWealth = wealths[0]
        secondWealth = wealths[1] if len(wealths) > 1 else 0.0
        if bestWealth <= 0 and len(candidates) > 2:
            return True
        scale = max(abs(bestWealth), abs(secondWealth), 1.0)
        if abs(bestWealth - secondWealth) / scale <= self.wealthMargin:
            return True

        agent = record.get("agent") or {}
        sugar = float(agent.get("sugar", 0.0) or 0.0)
        spice = float(agent.get("spice", 0.0) or 0.0)
        sugarMetabolism = float(agent.get("sugarMetabolism", 0.0) or 0.0)
        spiceMetabolism = float(agent.get("spiceMetabolism", 0.0) or 0.0)
        if sugarMetabolism > 0 and sugar <= sugarMetabolism * self.scarcityFactor:
            return True
        if spiceMetabolism > 0 and spice <= spiceMetabolism * self.scarcityFactor:
            return True
        return False

    def _isDifficultConversation(self, speakerState, listenerState):
        """Return True when a conversation should be generated by qwen3."""
        if speakerState.get("tribe") != listenerState.get("tribe"):
            return True
        for state in (speakerState, listenerState):
            sugar = float(state.get("sugar", 0.0) or 0.0)
            spice = float(state.get("spice", 0.0) or 0.0)
            sugarMetabolism = float(state.get("sugarMetabolism", 0.0) or 0.0)
            spiceMetabolism = float(state.get("spiceMetabolism", 0.0) or 0.0)
            if sugarMetabolism > 0 and sugar <= sugarMetabolism * self.scarcityFactor:
                return True
            if spiceMetabolism > 0 and spice <= spiceMetabolism * self.scarcityFactor:
                return True
        return False

    def choose_cell(self, agentState, candidates):
        if not candidates:
            return None
        if len(candidates) == 1:
            return 0
        record = {"agent": agentState, "candidates": candidates}
        if self._isDifficultDecision(record):
            decision = self.qwen.choose_cell(agentState, candidates)
            if decision is None:
                decision = self.nimble.choose_cell(agentState, candidates)
            return decision
        decision = self.nimble.choose_cell(agentState, candidates)
        if decision is None:
            decision = self.qwen.choose_cell(agentState, candidates)
        return decision

    def choose_cells(self, factionState):
        if not factionState:
            return {}

        decisions = {}
        simpleRecords = []
        difficultRecords = []
        for record in factionState:
            agent = record.get("agent") or {}
            agentID = str(agent.get("id"))
            candidates = record.get("candidates") or []
            if len(candidates) == 1:
                decisions[agentID] = 0
            elif self._isDifficultDecision(record):
                difficultRecords.append(record)
            else:
                simpleRecords.append(record)

        if simpleRecords:
            simpleDecisions = self.nimble.choose_cells(simpleRecords)
            decisions.update(simpleDecisions)
            # If nimble-v3 could not decide, ask qwen3 as a fallback.
            for record in simpleRecords:
                agentID = str((record.get("agent") or {}).get("id"))
                candidate = simpleDecisions.get(agentID)
                if candidate is None or not (0 <= candidate < len(record.get("candidates") or [])):
                    difficultRecords.append(record)

        if difficultRecords:
            qwenDecisions = self.qwen.choose_cells(difficultRecords)
            decisions.update(qwenDecisions)
            # If qwen3 is unavailable, let nimble-v3 make the remaining decisions.
            fallbackRecords = []
            for record in difficultRecords:
                agentID = str((record.get("agent") or {}).get("id"))
                candidate = qwenDecisions.get(agentID)
                if candidate is None or not (0 <= candidate < len(record.get("candidates") or [])):
                    fallbackRecords.append(record)
            if fallbackRecords:
                decisions.update(self.nimble.choose_cells(fallbackRecords))

        return decisions

    def choose_cells_parallel(self, factionStates):
        with ThreadPoolExecutor(max_workers=self.numParallel) as executor:
            decisions = executor.map(self.choose_cells, factionStates)
        return list(decisions)

    def talk(self, speakerState, listenerState):
        if self._isDifficultConversation(speakerState, listenerState):
            dialogue = self.qwen.talk(speakerState, listenerState)
            if dialogue is not None:
                return dialogue
            return self.nimble.talk(speakerState, listenerState)
        dialogue = self.nimble.talk(speakerState, listenerState)
        if dialogue is None:
            dialogue = self.qwen.talk(speakerState, listenerState)
        return dialogue

    def talk_parallel(self, pairs):
        with ThreadPoolExecutor(max_workers=self.numParallel) as executor:
            dialogues = executor.map(lambda pair: self.talk(pair[0], pair[1]), pairs)
        return list(dialogues)
